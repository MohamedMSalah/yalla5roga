import { z } from "zod";

export const outingIdParamsSchema = z.object({
  outingId: z.uuid(),
});

export const messageParamsSchema = outingIdParamsSchema.extend({ messageId: z.uuid() });
export const editMessageBodySchema = z.object({ text: z.string().trim().min(1).max(2000) });

export const chatHistoryQuerySchema = z.object({
  before: z.uuid().optional(),
  limit: z.coerce.number().int().min(1).max(100).optional(),
  messageId: z.uuid().optional(),
}).refine(({ messageId, before, limit }) => !messageId || (!before && limit == null), {
  message: "messageId cannot be combined with history pagination",
});

export const sendMessageBodySchema = z.object({
  text: z.string().trim().min(1).max(2000),
  /** Optional idempotency key generated by the client; a retry returns the stored message. */
  clientMessageId: z.uuid().optional(),
});

class PhoneTextField extends StatelessWidget {
  const PhoneTextField({
    super.key,
    required this.controller,
    this.label,
    this.hint,
    this.validator,
    this.validate = true,
    this.onChanged,
    this.allowInternational = false,
    this.callingCode = '+20',
    this.onCallingCodeChanged,
    this.textInputAction,
    this.autovalidateMode,
  });

  final TextEditingController controller;
  final String? label;
  final String? hint;
  final String? Function(String?)? validator;
  final bool validate;
  final ValueChanged<String>? onChanged;
  final bool allowInternational;
  final String callingCode;
  final ValueChanged<String>? onCallingCodeChanged;
  final TextInputAction? textInputAction;
  final AutovalidateMode? autovalidateMode;

  @override
  Widget build(BuildContext context) {
    final l10n = context.l10n;
    if (allowInternational) {
      return CustomTextField(
        controller: controller,
        onChanged: onChanged,
        label: label ?? l10n.phone,
        hint:
            hint ??
            (onCallingCodeChanged == null
                ? l10n.internationalPhoneHint
                : l10n.nationalPhoneNumberHint),
        keyboardType: TextInputType.phone,
        textDirection: TextDirection.ltr,
        validator: validator,
        prefix: onCallingCodeChanged == null
            ? null
            : Padding(
                padding: EdgeInsetsDirectional.only(start: 12.w, end: 8.w),
                child: Semantics(
                  label: l10n.countryCallingCode,
                  child: DropdownButtonHideUnderline(
                    child: DropdownButton<String>(
                      value: callingCode,
                      isDense: false,
                      itemHeight: null,
                      menuMaxHeight: MediaQuery.sizeOf(context).height * 0.5,
                      items: [
                        for (final code in _callingCodes)
                          DropdownMenuItem(
                            value: '+$code',
                            child: ConstrainedBox(
                              constraints: const BoxConstraints(minHeight: 48),
                              child: Center(child: Text(l10n.digits('+$code'))),
                            ),
                          ),
                      ],
                      onChanged: (value) {
                        if (value != null) onCallingCodeChanged!(value);
                      },
                      underline: const SizedBox.shrink(),
                      icon: const Icon(Icons.arrow_drop_down),
                    ),
                  ),
                ),
              ),
      );
    }
    // Keep phone rows LTR so "+20" stays on the left of the number in Arabic UI.
    return CustomTextField(
      controller: controller,
      onChanged: onChanged,
      label: label ?? l10n.phone,
      hint: hint ?? l10n.phoneHint,
      keyboardType: TextInputType.phone,
      textInputAction: textInputAction,
      textDirection: TextDirection.ltr,
      autovalidateMode: autovalidateMode,
      prefix: Padding(
        padding: EdgeInsetsDirectional.only(start: 12.w, end: 8.w),
        child: Row(
          mainAxisSize: MainAxisSize.min,
          children: [
            Icon(Icons.phone_outlined, size: 18.w, color: AppColors.brand600),
            6.gapW,
            Text(
              l10n.phoneCountryCode,
              style: TextStyle(
                fontWeight: FontWeight.w800,
                fontSize: Responsive.fontBody,
              ),
            ),
          ],
        ),
      ),
      inputFormatters: [
        InputFormatters.localizedDigits(
          arabicDisplay: l10n.locale.languageCode == 'ar',
          maxLength: Validators.localPhoneLength,
        ),
      ],
      validator:
          validator ??
          (validate ? (value) => Validators.phone(value, l10n) : null),
    );
  }

